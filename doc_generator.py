import io
from pptx import Presentation
from pptx.util import Inches, Pt
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_pdf(title: str, content: str) -> io.BytesIO:
    """
    যেকোনো বিষয়বস্তু থেকে পেশাদার PDF ফাইল তৈরি করে মেমোরিতে রিটার্ন করে (০ ডিস্ক খরচ)
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=50, leftMargin=50, topMargin=50, bottomMargin=50)
    styles = getSampleStyleSheet()
    
    title_style = styles['Heading1']
    body_style = styles['Normal']
    body_style.fontSize = 11
    body_style.leading = 14

    story = [
        Paragraph(title, title_style),
        Spacer(1, 20)
    ]

    for para in content.split("\n"):
        clean_para = para.strip()
        if clean_para:
            story.append(Paragraph(clean_para, body_style))
            story.append(Spacer(1, 10))

    doc.build(story)
    buffer.seek(0)
    return buffer

def generate_pptx(title: str, slides_data: list) -> io.BytesIO:
    """
    PowerPoint (.pptx) প্রেজেন্টেশন ফাইল তৈরি করে মেমোরিতে রিটার্ন করে
    slides_data = [{"title": "Slide 1", "content": "bullet 1\nbullet 2"}]
    """
    prs = Presentation()
    
    # Title Slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title
    slide.placeholders[1].text = "Generated by BullDers Executive AI"

    # Content Slides
    bullet_slide_layout = prs.slide_layouts[1]
    for s_info in slides_data:
        s = prs.slides.add_slide(bullet_slide_layout)
        s.shapes.title.text = s_info.get("title", "")
        body_shape = s.shapes.placeholders[1]
        tf = body_shape.text_frame
        tf.word_wrap = True
        
        lines = s_info.get("content", "").split("\n")
        if lines:
            tf.text = lines[0]
            for l in lines[1:]:
                p = tf.add_paragraph()
                p.text = l

    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)
    return buffer
